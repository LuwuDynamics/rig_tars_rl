void apply_gait_set(int idx)
{
    const GaitSet &g = kGaitSets[idx >= 1 && idx < kNumGaitSets ? idx : 0];
    s_ctrl.gait_f = g.f;
    s_ctrl.gait_b = g.b;
    s_ctrl.gait_turn = g.t;
    s_ctrl.gait_turn_r = g.tr;
    s_custom_mask = 0;                              /* a compiled set replaces every custom gait */
}
