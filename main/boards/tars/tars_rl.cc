/* One gait of the current set is replaced by parameters from the serial line (volatile; "learn gait N" or a reboot brings the compiled set back).
 * which = 'f' forward, 'b' backward, 't' turn left, 'r' turn right.  Returns 0, -1 (bad letter or a parameter outside the search ranges), -2 (walking now). */
int tars_rl_set_custom_gait(char which, const float p[15])
{
    static const char kSlots[] = "fbtr";
    const char *k = which ? strchr(kSlots, which) : nullptr;
    if (!k) return -1;
    const int slot = (int)(k - kSlots);
    tars_gait_t g = {p[0], p[1], p[2], p[3], p[4], p[5], p[6], p[7], p[8], p[9], p[10], p[11], p[12], p[13], p[14]};
    if (!tars_gait_in_range(&g)) return -1;
    if (s_enabled && s_ctrl.state >= TARS_S_WALK_F && s_ctrl.state <= TARS_S_TURN_R) return -2;
    xSemaphoreTake(s_mux, portMAX_DELAY);
    s_custom[slot] = g;
    if (slot == 0) s_ctrl.gait_f = &s_custom[0];
    else if (slot == 1) s_ctrl.gait_b = &s_custom[1];
    else if (slot == 2) s_ctrl.gait_turn = &s_custom[2];
    else s_ctrl.gait_turn_r = &s_custom[3];
    s_custom_mask |= 1u << slot;
    xSemaphoreGive(s_mux);
    RLOG("custom gait '%c': f %d mHz, hip a1/b1 %d/%d urad, lift c1/d1 %d/%d um, fb kp_h %d kd_h %d kp_z %d kd_z %d (millionths)", which, (int)lroundf(g.f * 1000.0f),
         (int)lroundf(g.a1 * 1e6f), (int)lroundf(g.b1 * 1e6f), (int)lroundf(g.c1 * 1e6f), (int)lroundf(g.d1 * 1e6f), (int)lroundf(g.kp_h * 1e6f), (int)lroundf(g.kd_h * 1e6f),
         (int)lroundf(g.kp_z * 1e6f), (int)lroundf(g.kd_z * 1e6f));
    return 0;
}

