bool tars_rl_history(int idx, char *buf, size_t n)
{
    portENTER_CRITICAL(&s_hist_lock);
    const uint32_t c = s_hist_count;
    const int cnt = (int)(c < (uint32_t)kHistN ? c : (uint32_t)kHistN);
    HistEntry h = {};
    const bool ok = idx >= 0 && idx < cnt;
    if (ok) h = s_hist[(c - (uint32_t)cnt + (uint32_t)idx) % kHistN];
    portEXIT_CRITICAL(&s_hist_lock);
    if (!ok) return false;
    char what[64];
    switch (h.kind) {
    case 0: snprintf(what, sizeof what, "%s -> %s  up=(%d,%d,%d) attempt %d", tars_state_name((tars_state_t)h.from), tars_state_name((tars_state_t)h.to), h.up[0], h.up[1], h.up[2], (int)h.attempts); break;
    case 1: snprintf(what, sizeof what, "learned mode ON%s", h.to ? " (dry run)" : ""); break;
    case 2: snprintf(what, sizeof what, "learned mode OFF"); break;
    case 4: snprintf(what, sizeof what, "boot, last reset: %s", reset_reason_name((int)h.to)); break;
    case 5: snprintf(what, sizeof what, "motion %s requested, speed %d%%", tars_rl_motion_name((int)h.to), (int)h.attempts); break;
    case 6: snprintf(what, sizeof what, "motion ended (%s)", h.to == 1 ? "played to the end" : (h.to == 2 ? "stopped" : (h.to == 3 ? "walking command" : (h.to == 4 ? "fall" : (h.to == 6 ? "legs tilted" : "request timed out"))))); break;
    default: snprintf(what, sizeof what, "autostart (mode %d)", (int)h.to); break;
    }
    snprintf(buf, n, "t=%u.%03us %s", (unsigned)(h.t_ms / 1000), (unsigned)(h.t_ms % 1000), what);
    return true;
}

