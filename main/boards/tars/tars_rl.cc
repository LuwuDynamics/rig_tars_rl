/* What the learned mode did (RAM ring, newest last): lets you read what happened while no PC was connected. */
struct HistEntry {
    uint32_t t_ms;
    int8_t kind;                                    /* 0 state change, 1 mode ON (to = dry run), 2 mode OFF, 3 autostart (to = auto mode), 4 boot (to = reset reason), 5 motion requested (to = index), 6 motion ended (to = reason) */
    int8_t from, to;
    int8_t up[3];                                   /* x100 */
    uint8_t attempts;                               /* kind 0: get-up attempts, kind 5: motion speed % */
};
constexpr int kHistN = 160;
HistEntry s_hist[kHistN];
volatile uint32_t s_hist_count = 0;
portMUX_TYPE s_hist_lock = portMUX_INITIALIZER_UNLOCKED;

void hist_push(int kind, int from, int to, const float up[3], int attempts)
{
    HistEntry h;
    h.t_ms = (uint32_t)(esp_timer_get_time() / 1000);
    h.kind = (int8_t)kind;
    h.from = (int8_t)from;
    h.to = (int8_t)to;
    for (int k = 0; k < 3; k++) h.up[k] = (int8_t)lroundf(fminf(fmaxf(up ? up[k] : 0.0f, -1.0f), 1.0f) * 100.0f);
    h.attempts = (uint8_t)(attempts < 0 ? 0 : (attempts > 255 ? 255 : attempts));
    portENTER_CRITICAL(&s_hist_lock);
    s_hist[s_hist_count % kHistN] = h;
    s_hist_count = s_hist_count + 1;
    portEXIT_CRITICAL(&s_hist_lock);
}

void mat3_mul(const float *R, const float *v, float *o)
{
    o[0] = R[0] * v[0] + R[1] * v[1] + R[2] * v[2];
    o[1] = R[3] * v[0] + R[4] * v[1] + R[5] * v[2];
    o[2] = R[6] * v[0] + R[7] * v[1] + R[8] * v[2];
}

void load_calibration()
{
    Settings st("tars_rl");
    const float legacy_flip = st.GetInt("flip", 0) == 1 ? -1.0f : 1.0f;                      /* older firmware: one flag for all three servos */
    for (int i = 0; i < 3; i++) s_sign[i] = st.GetInt(std::string("s") + std::to_string(i), 0) < 0 ? -1.0f : (st.GetInt(std::string("s") + std::to_string(i), 0) > 0 ? 1.0f : legacy_flip);
    s_swap_lr = st.GetInt("swap", 0) == 1;
    s_gait_set = st.GetInt("gait", kDefaultGaitSet);
    if (s_gait_set < 0 || s_gait_set >= kNumGaitSets) s_gait_set = kDefaultGaitSet;
    s_auto_mode = st.GetInt("auto", kDefaultAutoMode);
    if (s_auto_mode < 0 || s_auto_mode > 2) s_auto_mode = kDefaultAutoMode;
    s_getup_mode = st.GetInt("getup", kDefaultGetupMode);
    if (s_getup_mode < 0 || s_getup_mode > 2) s_getup_mode = kDefaultGetupMode;
    if (s_sign[0] < 0 || s_sign[1] < 0 || s_sign[2] < 0 || s_swap_lr) ESP_LOGW(TAG, "servo mapping loaded from NVS: signs %d %d %d swap_lr=%d", (int)s_sign[0], (int)s_sign[1], (int)s_sign[2], (int)s_swap_lr);
    if (st.GetInt("cal", 0) == 1) {
        for (int i = 0; i < 9; i++) s_R[i] = st.GetInt(std::string("r") + std::to_string(i), 0) * 1e-4f;
        s_calibrated = true;
        s_cal_loaded = calibrate_mode == 0;         /* both calibrations must exist at boot for autostart */
        RLOG("IMU calibration loaded from NVS");
    } else {
        ESP_LOGW(TAG, "IMU calibration missing");
    }
}

bool save_calibration(const float rotation[9])
{
    nvs_handle_t handle;
    esp_err_t err = nvs_open("tars_rl", NVS_READWRITE, &handle);
    if (err == ESP_OK) {
        for (int i = 0; i < 9 && err == ESP_OK; ++i) {
            const char key[] = {'r', static_cast<char>('0' + i), '\0'};
            err = nvs_set_i32(handle, key, (int32_t)lroundf(rotation[i] * 1e4f));
        }
        if (err == ESP_OK) err = nvs_set_i32(handle, "cal", 1);
        if (err == ESP_OK) err = nvs_commit(handle);
        nvs_close(handle);
    }
    if (err != ESP_OK) {
        RLOG("IMU calibration save failed: %s", esp_err_to_name(err));
        return false;
    }

    xSemaphoreTake(s_mux, portMAX_DELAY);
    memcpy(s_R, rotation, sizeof(s_R));
    s_mf_ready = false;
    tars_gyro_bias_reset(&s_gb);
    s_calibrated = true;
    xSemaphoreGive(s_mux);
    return true;
}

/* switch the learned mode on / off; cmds = walking commands (vx / vyaw) are passed to the supervisor */
void enable_mode(bool enable, bool dry_run, bool cmds)
{
    if (enable) {
        xSemaphoreTake(s_mux, portMAX_DELAY);
        s_mf_ready = false;
        tars_gyro_bias_reset(&s_gb);
        tars_ctrl_reset(&s_ctrl);
        s_last_step_us = 0;
        xSemaphoreGive(s_mux);
    }
    s_cmd_enabled = cmds;
    s_dry_run = dry_run;
    s_enabled = enable;
    RLOG("learned mode %s%s", enable ? "ON" : "OFF", (enable && dry_run) ? " (DRY RUN: servos not driven)" : "");
    hist_push(enable ? 1 : 2, -1, dry_run ? 1 : 0, s_up, 0);
    if (!enable) Reset();                           /* back to the nominal pose */
}

void imu_task(void *)
{
    TickType_t last = xTaskGetTickCount();
    for (;;) {
        vTaskDelayUntil(&last, pdMS_TO_TICKS(10));
        if (s_auto_mode > 0 && !s_auto_done && s_cal_loaded && calibrate_mode == 0 &&
            !s_enabled && esp_timer_get_time() > 4000000) {
            s_auto_done = true;                               /* once per power-up; the filter starts when the robot is still */
            enable_mode(true, false, s_auto_mode == 2);
            hist_push(3, -1, s_auto_mode, s_up, 0);
            RLOG("autostart: learned mode ON (%s)", s_auto_mode == 2 ? "stand, get up, walking commands accepted" : "stand + get up, walking commands ignored");
        }
        if (!s_enabled && !s_stream_imu && !s_upright_sampling) continue;
        const bool fresh = imu_read_once();               /* updates accel_x..z [m/s^2] and gyro_x..z [deg/s] */
        const float acc_f[3] = {accel_x, accel_y, accel_z};
        /* gyro in the accel frame: legacy imu.cc swaps x/y and the accel sign-flips x/y (180 deg about z) */
        const float gyr_f[3] = {-gyro_y * kDeg2Rad, -gyro_x * kDeg2Rad, gyro_z * kDeg2Rad};
        float acc_r[3], gyr_r[3];
        float up_local[3];
        bool filt_ready;
        xSemaphoreTake(s_mux, portMAX_DELAY);
        if (s_upright_sampling && !s_upright_ready) {
            if (!fresh) {
                tars_gyro_bias_reset(&s_upright_window);
            } else {
                s_upright_ready = tars_gyro_bias_start(&s_upright_window, acc_f, gyr_f, s_upright_acc);
            }
        }
        if (!fresh || (!s_enabled && !s_stream_imu)) {
            xSemaphoreGive(s_mux);
            continue;
        }
        mat3_mul(s_R, acc_f, acc_r);
        mat3_mul(s_R, gyr_f, gyr_r);
        bool just_started = false;
        if (!s_mf_ready) {
            /* Start the attitude filter only once the robot has been really still for 0.3 s; a start while the robot is being moved
             * gives a wrong attitude that the gated accelerometer correction removes only slowly.  The same window gives the gyro
             * zero-rate offset (the Tars IMUs have 0.1..0.17 rad/s of it, the training assumed 0.012). */
            float m[3];
            if (tars_gyro_bias_start(&s_gb, acc_r, gyr_r, m)) {
                tars_mahony_init_from_acc(&s_mf, m);
                s_mf_ready = true;
                just_started = true;
                s_last_imu_us = esp_timer_get_time();            /* else tars_rl_update() sees the previous session's timestamp: 'IMU stale' */
                tars_mahony_up_body(&s_mf, s_up);
                RLOG("attitude filter started, up x100 = (%d %d %d), gyro offset x100 deg/s = (%d %d %d)", (int)lroundf(s_up[0] * 100),
                     (int)lroundf(s_up[1] * 100), (int)lroundf(s_up[2] * 100), (int)lroundf(s_gb.bias[0] / kDeg2Rad * 100), (int)lroundf(s_gb.bias[1] / kDeg2Rad * 100),
                     (int)lroundf(s_gb.bias[2] / kDeg2Rad * 100));
            }
        }
        if (s_mf_ready && !just_started) {
            tars_gyro_bias_apply(&s_gb, acc_r, gyr_r);               /* subtract the offset (and follow its drift while static) */
            tars_mahony_update(&s_mf, gyr_r, acc_r, 0.01f);
            tars_mahony_up_body(&s_mf, s_up);
            memcpy(s_gyro, gyr_r, sizeof(s_gyro));
            s_imu_samples++;
            s_last_imu_us = esp_timer_get_time();
        }
        filt_ready = s_mf_ready;
        memcpy(up_local, s_up, sizeof(up_local));
        xSemaphoreGive(s_mux);

        if (s_stream_imu) {                               /* hand the sample to the logger */
            tars_log_imu_sample_t sm;
            sm.acc[0] = accel_x; sm.acc[1] = accel_y; sm.acc[2] = accel_z;
            sm.gyro[0] = gyro_x; sm.gyro[1] = gyro_y; sm.gyro[2] = gyro_z;
            for (int k = 0; k < 3; k++) sm.up[k] = filt_ready ? up_local[k] : 0.0f;
            const bool railed = fabsf(accel_x) > 19.0f || fabsf(accel_y) > 19.0f || fabsf(accel_z) > 19.0f;      /* a stuck accelerometer channel */
            sm.flags = (uint8_t)((filt_ready ? 1 : 0) | (s_calibrated ? 2 : 0) | (s_enabled ? 4 : 0) | (s_dry_run ? 8 : 0) | (imu_is_initialized() ? 0 : 16) |
                                 (railed ? 32 : 0));
            sm.state = s_enabled ? (int8_t)s_ctrl.state : (int8_t)-1;
            tars_log_sample(&sm);
        }
    }
}

/* simulator convention (hip q>0 = foot forward, lift z>0 = legs retract up) -> servo count offsets for WritePos() */
void compute_pos(const float q[2], float z, float pos[MOTOR_NUM])
{
    const float hl = fminf(fmaxf(q[0], -kHipLimit), kHipLimit);
    const float hr = fminf(fmaxf(q[1], -kHipLimit), kHipLimit);
    z = fminf(fmaxf(z, -kLiftLimit), kLiftLimit);
    pos[0] = pos[1] = pos[2] = 0.0f;
    const int li = s_swap_lr ? 1 : 0, ri = s_swap_lr ? 0 : 1;      /* motor[] index of the LEFT / RIGHT arm servo */
    pos[li] = s_sign[li] * kHipDir[li] * hl / kCountRad;
    pos[ri] = s_sign[ri] * kHipDir[ri] * hr / kCountRad;
    pos[2] = tars_lift_offset(s_sign[2] * kLiftSign * z * 1000.0f);
    for (int i = 0; i < MOTOR_NUM; i++) pos[i] = fminf(fmaxf(pos[i], -kMaxCounts), kMaxCounts);
}

void write_servos(const float q[2], float z)
{
    float pos[MOTOR_NUM];
    compute_pos(q, z, pos);
    if (!s_dry_run) WritePos(pos);
}

