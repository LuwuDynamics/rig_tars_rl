/*
 * tars_rl.cc - ESP32-S3 glue of the learned behaviours:
 *   100 Hz IMU task -> gyro offset + Mahony attitude filter -> tars_ctrl supervisor (500 Hz by default) -> servo targets.
 *   The supervisor (tars_ctrl.c, portable C) does the stand / walk / turn gaits with the gyro heading hold, the fall detection and the get-up
 *   (keyframes and / or the learned network); this file owns the hardware side: IMU axes, servo mapping, NVS settings, the history ring and the log-tool hooks.
 *
 * Servo mapping (confirmed on the real robot): ID1 = LEFT arm, ID2 = RIGHT arm; hip ID1 +count = foot forward, ID2 +count = foot backward;
 * lift_mm < 0 = legs retract upward.  Another unit with a different assembly: tars_rl_set_mapping3() (MCP self.tars.learned_mapping, `map` in the log tool).
 * IMU: the accel-frame -> robot-frame matrix s_R is stored in NVS after upright or two-pose calibration.
 */
