/* runtime tuning of the walking feedback (volatile: back to the searched gait at every power-up) */
void tars_rl_set_tune(int kp_pct, int kd_pct, int lpf_hz, int amp_pct, int rate_hz)
{
    auto clampi = [](int v, int lo, int hi) { return v < lo ? lo : (v > hi ? hi : v); };
    s_ctrl.fb_kp_scale = clampi(kp_pct, 0, 300) * 0.01f;
    s_ctrl.fb_kd_scale = clampi(kd_pct, 0, 300) * 0.01f;
    s_ctrl.fb_lpf_hz = (float)clampi(lpf_hz, 0, 50);
    s_ctrl.amp_scale = clampi(amp_pct, 20, 150) * 0.01f;
    const int hz = rate_hz >= 375 ? 500 : (rate_hz >= 175 ? 250 : (rate_hz >= 75 ? 100 : 50));
    s_step_us = 1000000 / hz;
    RLOG("tune: pitch feedback %d%%, rate feedback %d%%, rate low-pass %d Hz (0 = off), gait amplitude %d%%, controller %d Hz", clampi(kp_pct, 0, 300), clampi(kd_pct, 0, 300),
         clampi(lpf_hz, 0, 50), clampi(amp_pct, 20, 150), hz);
}

void tars_rl_get_tune(int out[5])
{
    out[0] = (int)lroundf(s_ctrl.fb_kp_scale * 100.0f);
    out[1] = (int)lroundf(s_ctrl.fb_kd_scale * 100.0f);
    out[2] = (int)lroundf(s_ctrl.fb_lpf_hz);
    out[3] = (int)lroundf(s_ctrl.amp_scale * 100.0f);
    out[4] = (int)(1000000 / s_step_us);
}

