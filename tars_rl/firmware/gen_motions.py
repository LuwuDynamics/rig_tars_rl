"""Generate tars_motions.h: some of the fun motions (rl/fun_motions.py, FUN_MOTIONS.md) as sampled servo-target tables for the supervisor's MOTION state.

The tables are the commands the simulator's Player actually sent to the servo model: the motion function sampled at 50 Hz and passed through the same speed limits
(hips 8 rad/s, lift 0.25 m/s) starting from the nominal pose, so what the firmware plays is exactly what was validated in the simulator.
Units in the table: hips 1e-3 rad, lift 1e-4 m (int16).  An emotion also carries the name of the screen emoji (face) that goes with it, NULL for the others.  A table starts and ends at the nominal pose (0, 0, 0).

usage: python firmware/gen_motions.py [--out firmware/generated] [--check]
       --check: only verify that the header in --out is what the current motion functions give (exit code 1 if not)
"""
import argparse
import math
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'rl'))
import fun_motions as fm                                  # noqa: E402
import fun_sim as fs                                      # noqa: E402

DT = 0.02                                                 # table period [s] = the simulator's control step
# the motions that are in the firmware: the TALL posture (standing on the arms, the torso pitches on the hips - the robot's normal stance) and the READY posture
# (arms retracted, the robot stands on its torso base and the arms swing freely: stability of that stance checked on the real robot 2026-11-02, 8 s, tilt within +-4 deg)
# (the sneeze was dropped: at full speed on the real robot its 0.2 s forward snap tipped the whole robot over, 2026-11-02; it stays in the simulator only)
NAMES = ['nod', 'bow', 'headbang',                                                 # show motions (tried on the real robot at 50 % and 100 %)
         'happy', 'sad', 'angry', 'scared', 'surprised', 'shy', 'curious', 'sleepy', 'proud', 'laugh', 'loving', 'impatient',     # emotions (TALL; tried on the real robot at 50 % and 100 %)
         'wave', 'cheer', 'windmill', 'robotdance', 'swim', 'twist']                                                             # arm motions (READY; simulator only until tried on the real robot)
MIN_TILT_LIMIT = 40.0                                     # deg: the abort threshold is max(this, peak pitch + 20 deg), rounded up to 5 deg, at most 80
MAX_TILT_LIMIT = 80.0
READY_TILT_LIMIT = 25.0                                    # deg: READY motions keep the torso upright on its base (simulator: <= 5 deg, real hold: <= 4 deg); more = it is tipping


def sample(name):
    fn = fm.MOTIONS[name]['fn']
    T = fm.MOTIONS[name]['T']
    n = int(round(T / DT)) + 1
    lim = np.array([fs.RATE_HIP * DT, fs.RATE_HIP * DT, fs.RATE_LIFT * DT])
    cur = np.zeros(3)
    rows = []
    for i in range(n):
        tgt = np.asarray(fn(i * DT), float)
        cur = cur + np.clip(tgt - cur, -lim, lim)
        rows.append(cur.copy())
    rows = np.array(rows)
    hl = np.round(rows[:, 0] * 1000.0).astype(int)
    hr = np.round(rows[:, 1] * 1000.0).astype(int)
    z = np.round(rows[:, 2] * 1e4).astype(int)
    assert abs(hl[-1]) <= 1 and abs(hr[-1]) <= 1 and abs(z[-1]) <= 1, '%s does not end at the nominal pose: %s' % (name, (hl[-1], hr[-1], z[-1]))
    assert abs(hl[0]) <= 1 and abs(hr[0]) <= 1 and abs(z[0]) <= 1, '%s does not start at the nominal pose' % name
    hl[-1] = hr[-1] = z[-1] = 0
    assert np.abs(hl).max() < 32000 and np.abs(z).max() < 32000
    peak = math.degrees(max(np.abs(hl).max(), np.abs(hr).max()) / 1000.0)
    ready = fm.MOTIONS[name]['family'] == 'ready'               # the arms swing, the torso does not pitch: the hip angle says nothing about the tilt
    limit = READY_TILT_LIMIT if ready else min(MAX_TILT_LIMIT, max(MIN_TILT_LIMIT, 5.0 * math.ceil((peak + 20.0) / 5.0)))
    speed = max(np.abs(np.diff(hl)).max(), np.abs(np.diff(hr)).max()) / 1000.0 / DT
    return dict(name=name, n=n, hl=hl, hr=hr, z=z, limit=limit, peak=peak, hip_speed=speed, face=fm.MOTIONS[name].get('face'), ready=ready)


def arr(name, suffix, v):
    body = []
    for i in range(0, len(v), 16):
        body.append('    ' + ', '.join('%d' % x for x in v[i:i + 16]) + ',')
    return 'static const int16_t tars_motion_%s_%s[%d] = {\n%s\n};\n' % (name, suffix, len(v), '\n'.join(body))


def make_header():
    out = ['/* AUTO-GENERATED by tars_rl/firmware/gen_motions.py from tars_rl/rl/fun_motions.py - DO NOT EDIT.',
           ' * Motion tables for the supervisor\'s MOTION state (tars_ctrl.h): servo targets every %d ms, hips in 1e-3 rad (q>0 = foot forward = the torso bows forward when the' % int(DT * 1000),
           ' * arms stand on the floor), lift in 1e-4 m (z<0 = arms push down = stand tall, z>0 = arms retracted: the robot stands on its torso base and the arms swing freely).',
           ' * Every table starts and ends at the nominal pose (0, 0, 0). */',
           '#ifndef TARS_MOTIONS_H', '#define TARS_MOTIONS_H', '#include <stdint.h>', '#include "tars_ctrl.h"', '']
    entries = []
    info = []
    for nm in NAMES:
        s = sample(nm)
        info.append(s)
        out.append('/* %s: %.2f s, %s %.0f deg, peak hip speed %.1f rad/s, aborts to FALLEN above %.0f deg */' % (nm, (s['n'] - 1) * DT, 'peak hip angle (arms retracted, the torso stays upright)' if s['ready'] else 'peak pitch', s['peak'], s['hip_speed'], s['limit']))
        out.append(arr(nm, 'hl', s['hl']))
        same = bool(np.array_equal(s['hl'], s['hr']))
        if not same:
            out.append(arr(nm, 'hr', s['hr']))
        out.append(arr(nm, 'z', s['z']))
        entries.append('    { "%s", %d, %.3ff, %.1ff, tars_motion_%s_hl, tars_motion_%s_%s, tars_motion_%s_z, %s },' % (nm, s['n'], DT, s['limit'], nm, nm, 'hl' if same else 'hr', nm,
                                                                                              '"%s"' % s['face'] if s['face'] else 'NULL'))
    out.append('static const tars_motion_t tars_motions[] = {')
    out.extend(entries)
    out.append('};')
    out.append('#define TARS_MOTION_COUNT %d' % len(NAMES))
    out.append('#endif')
    return '\n'.join(out) + '\n', info


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'firmware', 'generated'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text, info = make_header()
    path = os.path.join(a.out, 'tars_motions.h')
    if a.check:
        ok = os.path.exists(path) and open(path).read() == text
        print('tars_motions.h is %s' % ('up to date' if ok else 'STALE'))
        sys.exit(0 if ok else 1)
    os.makedirs(a.out, exist_ok=True)
    open(path, 'w').write(text)
    flash = sum(2 * (s['n'] * (2 if not np.array_equal(s['hl'], s['hr']) else 1) + s['n']) for s in info)
    print('wrote %s  (%d motions, %d bytes of tables)' % (path, len(info), flash))
    for s in info:
        print('  %-9s %4d samples  %.2f s  peak pitch %4.0f deg  hip speed %.1f rad/s  tilt limit %.0f deg' % (s['name'], s['n'], (s['n'] - 1) * DT, s['peak'], s['hip_speed'], s['limit']))
