"""Generate an ADDITIONAL gait set header (symbols suffixed _v5) for the firmware; the original set (gen_params.py -> tars_gait_params.h) stays untouched.
usage: python firmware/gen_params_set.py --fwd runs/walk_cma_cal/fwd_c4.json [--back ...] [--turn ...] [--turnr ...] --suffix v5 --out firmware/generated
A gait that is not given falls back to NULL (the supervisor then stands instead of walking that way)."""
import argparse, json, os
NAMES = ['q0', 'a1', 'b1', 'a2', 'b2', 'z0', 'c1', 'd1', 'c2', 'd2', 'f', 'kp_h', 'kd_h', 'kp_z', 'kd_z']

def lit(v):
    s = f'{v:.7g}'
    if not any(c in s for c in '.eE'):
        s += '.0'                                   # 0 -> 0.0 ("0f" is not a C float literal)
    return s + 'f'


def gait_c(name, p):
    return f"static const tars_gait_t {name} = {{ " + ', '.join(lit(p[n]) for n in NAMES) + ' };\n'

ap = argparse.ArgumentParser()
ap.add_argument('--fwd', required=True); ap.add_argument('--fwd_fast'); ap.add_argument('--back'); ap.add_argument('--turn'); ap.add_argument('--turnr')
ap.add_argument('--suffix', default='v5'); ap.add_argument('--out', default='firmware/generated'); ap.add_argument('--note', default='')
a = ap.parse_args()
S, U = a.suffix, a.suffix.upper()
os.makedirs(a.out, exist_ok=True)
h = [f'/* AUTO-GENERATED by firmware/gen_params_set.py - DO NOT EDIT.  Gait set "{S}": {a.note} */', f'#ifndef TARS_GAIT_PARAMS_{U}_H', f'#define TARS_GAIT_PARAMS_{U}_H', '#include "tars_ctrl.h"', '']
for key, var, macro, label in (('fwd', f'tars_gait_fwd_{S}', None, 'forward'), ('fwd_fast', f'tars_gait_fwd_{S}_fast', None, 'forward, faster / less robust variant'), ('back', f'tars_gait_back_{S}', f'TARS_GAIT_BACK_{U}_PTR', 'backward'),
                               ('turn', f'tars_gait_turn_{S}', f'TARS_GAIT_TURN_{U}_PTR', 'turn left (right = mirrored unless a dedicated right gait is given)'),
                               ('turnr', f'tars_gait_turn_r_{S}', f'TARS_GAIT_TURNR_{U}_PTR', 'dedicated right turn')):
    path = getattr(a, key)
    if path:
        h.append(f'/* {label}: {path} */')
        h.append(gait_c(var, json.load(open(path))['params']))
        if macro:
            h.append(f'#define {macro} (&{var})')
    elif macro:
        h.append(f'#define {macro} NULL')
h.append('#endif')
out = os.path.join(a.out, f'tars_gait_params_{S}.h')
open(out, 'w').write('\n'.join(h) + '\n')
print('wrote', out)
