"""Export a trained actor to C (weights header) and record cross-check vectors for the host unit test.

usage: python rl/export_c.py runs/walk_res_a/best.pt walk firmware/generated
writes:  <out>/tars_rl_<name>_weights.h   (const float arrays + tars_mlp_t)
         <out>/policy_<name>.json          (config the firmware must use)
         <out>/vectors_<name>.txt          (obs/action pairs + full step replay + IMU stream for tests)
"""
import argparse
import json
import math
import os
import sys

import numpy as np
import torch

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'sim'))
sys.path.insert(0, os.path.join(ROOT, 'rl'))
from tars_env import TarsEnv, DT, OBS_DIM                 # noqa: E402
from evaluate import load_policy                          # noqa: E402


def fold(ck):
    sd = ck['net']
    mean = np.asarray(ck['onorm']['mean'], dtype=np.float64)
    std = np.sqrt(np.asarray(ck['onorm']['var'], dtype=np.float64) + 1e-8)
    W1 = sd['actor.0.weight'].double().numpy()
    b1 = sd['actor.0.bias'].double().numpy()
    W1f = W1 / std[None, :]
    b1f = b1 - W1f @ mean
    W2, b2 = sd['actor.2.weight'].double().numpy(), sd['actor.2.bias'].double().numpy()
    W3, b3 = sd['actor.4.weight'].double().numpy(), sd['actor.4.bias'].double().numpy()
    lo, hi = mean - 10.0 * std, mean + 10.0 * std
    return [W1f, b1f, W2, b2, W3, b3, lo, hi]


def c_array(name, arr):
    flat = np.asarray(arr, dtype=np.float32).ravel()
    lines = []
    for i in range(0, len(flat), 8):
        lines.append('    ' + ', '.join(f'{v:.9g}f' for v in flat[i:i + 8]) + ',')
    return f'static const float {name}[{len(flat)}] = {{\n' + '\n'.join(lines) + '\n};\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('ckpt')
    ap.add_argument('name')
    ap.add_argument('out')
    ap.add_argument('--steps', type=int, default=300)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    ck = torch.load(a.ckpt, weights_only=False)
    W1, b1, W2, b2, W3, b3, lo, hi = fold(ck)
    n_in, n_h1, n_h2, n_out = W1.shape[1], W1.shape[0], W2.shape[0], W3.shape[0]
    nbytes = 4 * (W1.size + b1.size + W2.size + b2.size + W3.size + b3.size)
    ev = json.loads(ck['args'].get('env_kw') or '{}')
    residual = int(ev.get('action_mode', 'direct') == 'residual')
    pre = f'tars_{a.name}'
    hdr = [f'/* AUTO-GENERATED by rl/export_c.py from {os.path.basename(os.path.dirname(a.ckpt))}/{os.path.basename(a.ckpt)} (iter {ck["it"]}). DO NOT EDIT. */',
           f'#ifndef TARS_RL_{a.name.upper()}_WEIGHTS_H', f'#define TARS_RL_{a.name.upper()}_WEIGHTS_H',
           '#include "tars_rl_core.h"',
           f'/* {n_in}-{n_h1}-{n_h2}-{n_out} tanh MLP, {nbytes/1024:.1f} KiB; observation normalisation folded into layer 1 */',
           f'#define {pre.upper()}_RESIDUAL {residual}',
           f'#define {pre.upper()}_ACT_SLEW {float(ev.get("act_slew") or 0.0):.6g}f   /* max change of the normalised action per 20 ms step (0 = unlimited) */']
    for nm, arr in (('w1', W1), ('b1', b1), ('w2', W2), ('b2', b2), ('w3', W3), ('b3', b3), ('lo', lo), ('hi', hi)):
        hdr.append(c_array(f'{pre}_{nm}', arr))
    hdr.append(f'static const tars_mlp_t {pre}_mlp = {{ {n_in}, {n_h1}, {n_h2}, {n_out}, {pre}_w1, {pre}_b1, {pre}_w2, {pre}_b2, {pre}_w3, {pre}_b3, {pre}_lo, {pre}_hi }};')
    hdr.append('#endif')
    open(os.path.join(a.out, f'tars_rl_{a.name}_weights.h'), 'w').write('\n'.join(hdr) + '\n')
    cfg_env = dict(hip_scale=0.6, lift_scale=0.014, gait_freq=1.25, res_hip=0.25, res_lift=0.008, amp_per_vx=1000.0,
                   amp_per_wz=30.0, yaw_sign=-1.0)
    cfg_env.update({k: v for k, v in ev.items() if k in cfg_env})
    act_slew = float(ev.get('act_slew') or 0.0)
    cfg_env['act_slew'] = act_slew
    meta = dict(name=a.name, residual=residual, obs_dim=n_in, act_dim=n_out, params=nbytes // 4, bytes=nbytes,
                train_iter=ck['it'], env=cfg_env, task=ck['args']['task'])
    json.dump(meta, open(os.path.join(a.out, f'policy_{a.name}.json'), 'w'), indent=1)

    # ----------------------------------------------------------------- test vectors
    fn, _ = load_policy(a.ckpt)
    kw = dict(task=ck['args']['task'], randomize=True, difficulty=1.0, max_steps=a.steps + 5)
    kw.update(ev)
    env = TarsEnv(seed=1234, **kw)
    obs, _ = env.reset()
    rows = []   # per step: inputs seen by the policy + expected outputs
    imu_rows = []
    f0 = dict(phase=env.phase, prev_frame=env.prev_frame.copy())
    # replay data: capture inputs at decision time
    pending = None
    for i in range(a.steps):
        up = env.up_ctrl().copy()                         # what the policy sees: lagged by the simulated IMU/control delay (0 = the newest)
        gyro = np.array(env.gyro_ctrl()).copy()
        qm = env.q_meas.copy()
        cmd = env.cmd.copy()
        phase = env.phase
        a_pol = fn(obs)
        obs, r, d, info = env.step(a_pol)
        rows.append(np.concatenate([up, gyro, qm, cmd, [phase], a_pol, env.a_prev]))   # a_prev == total action just applied
        if d:
            break
    # IMU stream for the Mahony check: replay raw accel/gyro samples into a fresh Python filter
    from tars_env import Mahony
    env2 = TarsEnv(seed=77, task='walk', randomize=True, difficulty=1.0, max_steps=400, push_prob_per_s=1.0)
    env2.reset()
    filt = Mahony(kp=2.0)
    acc0, gyr0 = env2._read_imu()
    filt.init_from_acc(acc0)
    rng = np.random.default_rng(0)
    for i in range(400):
        a_ = np.clip(rng.normal(0, 0.4, 3), -1, 1) if i < 200 else np.zeros(3)
        import mujoco
        env2.d.ctrl[:] = [a_[0] * 0.3, a_[1] * 0.3, a_[2] * 0.01]
        mujoco.mj_step(env2.m, env2.d, nstep=5)
        acc, gyr = env2._read_imu()
        filt.update(gyr, acc, 0.01)
        imu_rows.append(np.concatenate([gyr, acc, filt.up_body()]))
    with open(os.path.join(a.out, f'vectors_{a.name}.txt'), 'w') as f:
        f.write(f'{len(rows)} {len(imu_rows)} {int(f0["phase"]*1e6)} {residual}\n')
        f.write(' '.join(f'{v:.9g}' for v in f0['prev_frame']) + '\n')
        for r_ in rows:
            f.write(' '.join(f'{v:.9g}' for v in r_) + '\n')
        for r_ in imu_rows:
            f.write(' '.join(f'{v:.9g}' for v in r_) + '\n')
        f.write(f'{acc0[0]:.9g} {acc0[1]:.9g} {acc0[2]:.9g}\n')
    print(f'exported {a.name}: {n_in}-{n_h1}-{n_h2}-{n_out}, {nbytes/1024:.1f} KiB, residual={residual}, {len(rows)} replay steps')


if __name__ == '__main__':
    main()
