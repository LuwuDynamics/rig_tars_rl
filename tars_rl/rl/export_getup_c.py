"""Export the learned get-up actor to C: weights header for the firmware + a small test-vector header for the host parity test.

usage: python rl/export_getup_c.py checkpoints/getup_ppo_c3/final_it500.pt runs/export [--board ../main/boards/tars]
writes  <out>/tars_rl_getup_nn_weights.h   (tars_getup_nn_mlp: 28-128-128-3 tanh MLP, observation normalisation folded into layer 1)
        <out>/getup_nn_vectors.h           (observations the policy saw in GetupEnv rollouts and the network's outputs: the C code must reproduce them)
"""
import argparse
import os
import shutil
import sys

import numpy as np
import torch

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
for p in ('sim', 'rl', 'calib'):
    sys.path.insert(0, os.path.join(ROOT, p))
from export_c import fold                               # noqa: E402
from getup_env import GetupEnv                           # noqa: E402
from evaluate import load_policy                         # noqa: E402
from eval_cal import calibrated_kwargs                   # noqa: E402


def c_array(name, arr):
    """float array as C source; every literal has a decimal point or an exponent (a bare '0f' or '1f' is not valid C)"""
    flat = np.asarray(arr, dtype=np.float32).ravel()

    def lit(v):
        s = '%.9g' % v
        if not any(ch in s for ch in '.eEn'):
            s += '.0'
        return s + 'f'
    lines = ['    ' + ', '.join(lit(v) for v in flat[i:i + 8]) + ',' for i in range(0, len(flat), 8)]
    return f'static const float {name}[{len(flat)}] = {{\n' + '\n'.join(lines) + '\n};\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('ckpt')
    ap.add_argument('out')
    ap.add_argument('--board', default='')
    ap.add_argument('--n', type=int, default=96)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    ck = torch.load(a.ckpt, weights_only=False)
    W1, b1, W2, b2, W3, b3, lo, hi = fold(ck)
    n_in, n_h1, n_h2, n_out = W1.shape[1], W1.shape[0], W2.shape[0], W3.shape[0]
    nbytes = 4 * (W1.size + b1.size + W2.size + b2.size + W3.size + b3.size)
    pre = 'tars_getup_nn'
    hdr = [f'/* AUTO-GENERATED by rl/export_getup_c.py from {os.path.basename(os.path.dirname(a.ckpt))}/{os.path.basename(a.ckpt)} (iter {ck["it"]}). DO NOT EDIT. */',
           '#ifndef TARS_RL_GETUP_NN_WEIGHTS_H', '#define TARS_RL_GETUP_NN_WEIGHTS_H', '#include "tars_rl_core.h"',
           f'/* learned get-up: {n_in}-{n_h1}-{n_h2}-{n_out} tanh MLP, {nbytes/1024:.1f} KiB.  Observation: [t/10 s, 0, 0, 0, frame, frame 20 ms earlier], frame = [-up(3), gyro/4 (3), hips/2.4 rad (2), lift/14 mm, previous action (3)] */']
    for nm, arr in (('w1', W1), ('b1', b1), ('w2', W2), ('b2', b2), ('w3', W3), ('b3', b3), ('lo', lo), ('hi', hi)):
        hdr.append(c_array(f'{pre}_{nm}', arr))
    hdr.append(f'static const tars_mlp_t {pre}_mlp = {{ {n_in}, {n_h1}, {n_h2}, {n_out}, {pre}_w1, {pre}_b1, {pre}_w2, {pre}_b2, {pre}_w3, {pre}_b3, {pre}_lo, {pre}_hi }};')
    hdr.append('#endif')
    path = os.path.join(a.out, 'tars_rl_getup_nn_weights.h')
    open(path, 'w').write('\n'.join(hdr) + '\n')
    # test vectors: what the policy saw and answered in rollouts (back / front starts, both plants)
    fn, _ = load_policy(a.ckpt)
    args = ck['args']
    cal = calibrated_kwargs(lag=1, lag_jitter=1)
    cal.pop('ctrl_dt', None)
    O, A = [], []
    k = 0
    while len(O) < a.n:
        env = GetupEnv(seed=900 + k, plant_cal=cal, plant_mix=(1.0 if k % 2 == 0 else 0.0), continue_after_success=False, max_steps=400,
                       getup_init=dict(kind=('back', 'front')[k % 4 // 2], hip=(0.0, 0.0)), obs_q_mode='cmd', imu_clip=True)
        obs, _ = env.reset()
        for i in range(80):
            act = fn(obs)
            if i % 2 == 0 and len(O) < a.n:
                O.append(obs.copy())
                A.append(act.copy())
            obs, r, d, info = env.step(act)
            if d:
                break
        k += 1
    vec = ['/* AUTO-GENERATED test vectors for the learned get-up network (host test): observation -> action of the exported network */',
           f'#define TARS_GETUP_NN_NVEC {len(O)}',
           c_array('tars_getup_nn_test_obs', np.array(O)), c_array('tars_getup_nn_test_act', np.array(A))]
    open(os.path.join(a.out, 'getup_nn_vectors.h'), 'w').write('\n'.join(vec) + '\n')
    print('exported %s: %d-%d-%d-%d, %.1f KiB, %d test vectors' % (path, n_in, n_h1, n_h2, n_out, nbytes / 1024, len(O)))
    if a.board:
        shutil.copy(path, os.path.join(a.board, 'tars_rl_getup_nn_weights.h'))
        print('copied to', a.board)


if __name__ == '__main__':
    main()
